import { build } from 'vite'
import tailwindcss from '@tailwindcss/vite'
import { viteSingleFile } from 'vite-plugin-singlefile'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'

/**
 * Build every MCP App into one self-contained HTML file, written as a text
 * module the Worker serves (`src/<app>/app-html.generated.ts`).
 *
 * An App is any `src/<app>/app/index.html`. `--check` fails when a committed
 * module is stale, so `npm run check` catches an App edited without a rebuild.
 *
 *   npm run app:build            # every App
 *   npm run app:build -- <app>   # one App, by its src/ directory name
 */
const check = process.argv.includes('--check')
const only = process.argv.slice(2).filter((arg) => !arg.startsWith('--'))

const apps = (await readdir('src', { withFileTypes: true }))
  .filter(
    (entry) => entry.isDirectory() && existsSync(path.join('src', entry.name, 'app/index.html'))
  )
  .map((entry) => entry.name)
  .filter((name) => only.length === 0 || only.includes(name))
  .sort()

const stale: string[] = []
for (const name of apps) {
  const outDir = path.resolve('.mcp-apps-build', name)
  await build({
    configFile: false,
    logLevel: 'error',
    root: path.join('src', name, 'app'),
    plugins: [tailwindcss(), viteSingleFile()],
    build: { outDir, emptyOutDir: true, minify: true }
  })
  const html = await readFile(path.join(outDir, 'index.html'), 'utf8')
  const generated = `// Generated by npm run app:build. Do not edit.\nexport const appHtml = ${JSON.stringify(html)}\n`
  const target = path.join('src', name, 'app-html.generated.ts')
  if (check) {
    const current = existsSync(target) ? await readFile(target, 'utf8') : ''
    if (current !== generated) stale.push(target)
  } else {
    await writeFile(target, generated)
    console.log(`built ${target} (${Math.round(html.length / 1024)} KB)`)
  }
}
if (stale.length) throw new Error(`Stale MCP App HTML: ${stale.join(', ')}. Run npm run app:build.`)
